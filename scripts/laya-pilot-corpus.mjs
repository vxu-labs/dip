export function corpus() {
  return families.flatMap(
    ([label, scope, enOld, enNew, heOld, heNew], family) => {
      const [oldScope, newScope = oldScope] = scope.split("|");
      return [
        ["en", enOld, enNew],
        ["he", heOld, heNew],
        ["cross", heOld, enNew],
      ].map(([language, existing, request]) => ({
        id: `pair-${String(family).padStart(2, "0")}-${language}`,
        family,
        language,
        expected: label,
        identity: label === "same",
        optionRotation: family % 4,
        state: {
          existingTask: {
            title: existing,
            scope: oldScope,
            status: family % 2 ? "verified" : "backlog",
          },
          newRequest: { text: request, scope: newScope },
        },
      }));
    },
  );
}
